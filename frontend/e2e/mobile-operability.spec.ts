import { expect, test } from "@playwright/test";
import {
  installFragmentableSse,
  installSession,
  mockApi,
  submission,
} from "./fixtures";

test.describe("Case-29: Mobile Operability of Role-Critical Actions (RP-04, REQ-218)", () => {
  const viewports = [
    { name: "360px Phone", width: 360, height: 800 },
    { name: "768px Tablet", width: 768, height: 1024 },
  ];

  for (const vp of viewports) {
    test.describe(`Viewport ${vp.name} (${vp.width}x${vp.height})`, () => {
      test.use({ viewport: { width: vp.width, height: vp.height } });

      test("1. Contributor: Submit and Save Draft reachable without horizontal scroll", async ({ page }) => {
        await installSession(page, "contributor");
        await installFragmentableSse(page);
        await mockApi(page, "contributor");

        await page.goto("/submissions/new");

        // Verify sticky bottom action bar exists
        const bottomBar = page.locator(".sub-guard-panel");
        await expect(bottomBar).toBeVisible();

        // Verify forward navigation / action is present
        const nextOrSubmit = bottomBar.locator(".sub-step-panel-btn").last();
        await expect(nextOrSubmit).toBeVisible();

        // Verify no horizontal overflow on phone/tablet viewport
        const hasHorizontalScroll = await page.evaluate(() => {
          return document.documentElement.scrollWidth > window.innerWidth;
        });
        expect(hasHorizontalScroll).toBe(false);
      });

      test("2. Moderator: Deep link opens review with the lock held and decision actions reachable", async ({ page }) => {
        await installSession(page, "moderator");
        await installFragmentableSse(page);
        const api = await mockApi(page, "moderator", {
          // The real backend answers the lock POST with the lock it granted.
          [`POST /api/v1/validation/${submission.id}/lock`]: {
            id: "lock-e2e",
            submissionId: submission.id,
            lockedById: "test-moderator",
            lockedByEmail: "moderator@example.invalid",
            acquiredAt: new Date().toISOString(),
            expiresAt: new Date(Date.now() + 15 * 60_000).toISOString(),
          },
        });

        // Deep link to review mode as generated by NotificationEventListener (T-01, T-11)
        await page.goto(`/queue?submissionId=${submission.id}&mode=review`);

        // The lock is acquired automatically and the decision actions are in the action bar
        await expect(page.getByText(/Locked to you/)).toBeVisible({ timeout: 10_000 });
        for (const name of ["Approve", "Request Revision", "Reject"]) {
          await expect(page.getByRole("button", { name, exact: true })).toBeInViewport();
        }
        expect(api.count("POST", `/api/v1/validation/${submission.id}/lock`)).toBe(1);

        // Deep-link params are removed so a reload does not re-open / re-lock
        await expect(page).toHaveURL(/\/queue$/);

        const hasHorizontalScroll = await page.evaluate(() => {
          return document.documentElement.scrollWidth > window.innerWidth;
        });
        expect(hasHorizontalScroll).toBe(false);
      });

      test("3. Administrator: Calendar reschedule modal reachable without overflow", async ({ page }) => {
        await installSession(page, "admin");
        await installFragmentableSse(page);
        const api = await mockApi(page, "admin", {
          "/api/v1/calendar": [
            {
              id: submission.id,
              title: "Mobile Calendar Event",
              institutionId: submission.institutionId,
              institutionName: submission.institutionName,
              institutionCode: "CIT",
              status: "scheduled",
              scheduledAt: "2026-10-25T02:00:00Z",
              publishedAt: null,
              locked: false,
              mine: false,
              originalScheduledAt: "2026-10-25T02:00:00Z",
              moderatorRescheduleCount: 0,
            },
          ],
          [`PATCH /api/v1/submissions/${submission.id}/reschedule`]: { id: submission.id },
        });

        await page.goto("/calendar");
        const event = page.locator(".cal-event-pill").first();
        await expect(event).toBeVisible({ timeout: 10_000 });
        const target = page.locator('td[data-date="2026-10-27"]').first();
        await target.scrollIntoViewIfNeeded();

        // Drag the scheduled post two days later
        const from = (await event.boundingBox())!;
        const to = (await target.boundingBox())!;
        await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
        await page.mouse.down();
        await page.mouse.move(from.x + from.width / 2 + 6, from.y + from.height / 2 + 6, { steps: 5 });
        await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 15 });
        await page.mouse.up();

        const modal = page.getByRole("dialog", { name: "Confirm calendar reschedule" });
        await expect(modal).toBeVisible();
        await modal.getByPlaceholder("Why is this being rescheduled?").fill("Venue moved to a later date");
        const confirm = modal.getByRole("button", { name: "Confirm", exact: true });
        await expect(confirm).toBeInViewport();
        const modalBox = (await modal.boundingBox())!;
        expect(modalBox.width).toBeLessThanOrEqual(vp.width);
        await confirm.click();
        await expect.poll(() => api.count("PATCH", `/api/v1/submissions/${submission.id}/reschedule`)).toBe(1);

        const hasHorizontalScroll = await page.evaluate(() => {
          return document.documentElement.scrollWidth > window.innerWidth;
        });
        expect(hasHorizontalScroll).toBe(false);
      });

      test("4. Administrator: Failed-publication link opens the post with resolution actions reachable", async ({ page }) => {
        await installSession(page, "admin");
        await installFragmentableSse(page);
        await mockApi(page, "admin", {
          "/api/v1/resolution/failures/page": {
            items: [
              {
                id: "fail-1",
                submissionId: submission.id,
                title: "Failed Post Example",
                failedAt: "2026-10-15T08:00:00Z",
                status: "publish_failed",
                errorSummary: "Page Access Token Expired (Graph API 190)",
                canRetry: true,
                canManualPublish: true,
              },
            ],
            page: 0,
            pageSize: 20,
            totalCount: 1,
            totalPages: 1,
            hasNext: false,
            failureCount: 1,
          },
        });

        // Publish-failed notification link (NotificationEventListener, T-06). On phone/tablet the
        // linked post opens full-screen, so assert the recovery actions rather than the tab strip.
        await page.goto(`/queue?tab=failed&submissionId=${submission.id}`);
        await expect(page.getByRole("button", { name: "Retry", exact: true })).toBeInViewport({ timeout: 10_000 });
        await expect(page.getByRole("button", { name: "Start Manual Publish" })).toBeInViewport();

        const hasHorizontalScroll = await page.evaluate(() => {
          return document.documentElement.scrollWidth > window.innerWidth;
        });
        expect(hasHorizontalScroll).toBe(false);
      });

      test("5. Invitee: Accept invitation form and submit button visible without overflow", async ({ page }) => {
        await page.route("**/api/v1/invitations/validate*", async (route) => {
          await route.fulfill({
            status: 200,
            contentType: "application/json",
            body: JSON.stringify({
              recipientEmail: "invitee@example.invalid",
              assignedRole: "contributor",
              institutionName: "Cebu Institute of Technology - University",
              expiresAt: new Date(Date.now() + 86400000).toISOString(),
            }),
          });
        });

        await page.goto("/invite?token=valid-mobile-test-token");

        // Invitation details load and the activation submit button is reachable
        await expect(page.locator("#inv-email-display")).toHaveText("invitee@example.invalid");
        const activateButton = page.locator("#inv-btn");
        await activateButton.scrollIntoViewIfNeeded();
        await expect(activateButton).toBeInViewport();

        // Check horizontal overflow
        const hasHorizontalScroll = await page.evaluate(() => {
          return document.documentElement.scrollWidth > window.innerWidth;
        });
        expect(hasHorizontalScroll).toBe(false);
      });
    });
  }
});

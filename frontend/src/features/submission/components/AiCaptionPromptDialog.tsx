import { useEffect, useId, useMemo, useRef, useState } from "react";
import { createPortal } from "react-dom";
import { AI_CAPTION_PROMPT_MAX_LENGTH } from "../../../api/aiApi";
import type { CaptionTone, CaptionVariant } from "../../../api/aiApi";
import type { AiCaptionState } from "../../../hooks/useAiCaptionAssist";
import "./AiCaptionPromptDialog.css";

interface Props {
  open: boolean;
  state: AiCaptionState;
  hasImageAssets: boolean;
  existingCaption: string;
  initialVariant?: CaptionVariant | null;
  isUnsaved?: boolean;
  onClose: () => void;
  onSubmit: (prompt: string, tone: CaptionTone) => Promise<unknown> | unknown;
  onApprove: (
    caption: string,
    tone: CaptionTone,
    action?: "use" | "use_then_edited",
  ) => void;
}

const TONE_OPTIONS: Array<{
  tone: CaptionTone;
  label: string;
}> = [
  { tone: "professional", label: "Professional" },
  { tone: "community", label: "Community" },
  { tone: "energetic", label: "Energetic" },
];

export default function AiCaptionPromptDialog({
  open,
  state,
  hasImageAssets,
  existingCaption,
  initialVariant = null,
  isUnsaved = false,
  onClose,
  onSubmit,
  onApprove,
}: Props) {
  const [selectedTone, setSelectedTone] = useState<CaptionTone>("professional");
  const [prompt, setPrompt] = useState("");
  const [captionResult, setCaptionResult] = useState("");
  const [editing, setEditing] = useState(false);
  const [editText, setEditText] = useState("");
  const [copied, setCopied] = useState(false);
  const titleId = useId();
  const toneSelectId = useId();
  const autoGeneratedRef = useRef(false);
  const chatTextareaRef = useRef<HTMLTextAreaElement | null>(null);
  const onSubmitRef = useRef(onSubmit);
  onSubmitRef.current = onSubmit;
  const initialVariantRef = useRef(initialVariant);
  initialVariantRef.current = initialVariant;

  const isLoading = state === "loading";
  const promptLength = prompt.length;
  const isOverLimit = promptLength > AI_CAPTION_PROMPT_MAX_LENGTH;

  const contextLabel = useMemo(() => {
    if (hasImageAssets && existingCaption.trim().length > 0) {
      return "Using selected media and the current caption draft.";
    }
    if (hasImageAssets) {
      return "Using selected media to shape a new caption draft.";
    }
    if (existingCaption.trim().length > 0) {
      return "Using the current caption draft as reference.";
    }
    return "Generating a new caption draft from scratch.";
  }, [existingCaption, hasImageAssets]);

  useEffect(() => {
    if (!open) {
      autoGeneratedRef.current = false;
      queueMicrotask(() => {
        setPrompt("");
        setCaptionResult("");
        setEditText("");
        setEditing(false);
        setSelectedTone("professional");
        setCopied(false);
      });
      return;
    }

    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape" && !isLoading) {
        onClose();
      }
    };

    window.addEventListener("keydown", handleKeyDown);
    return () => {
      document.body.style.overflow = previousOverflow;
      window.removeEventListener("keydown", handleKeyDown);
    };
  }, [isLoading, onClose, open]);

  // On open: restore existing generated caption if present, otherwise auto-generate once
  useEffect(() => {
    if (!open || autoGeneratedRef.current) return;
    autoGeneratedRef.current = true;
    const existing = initialVariantRef.current;
    if (existing?.caption) {
      setCaptionResult(existing.caption);
      setEditText(existing.caption);
      setSelectedTone(existing.tone || "professional");
      setEditing(false);
      return;
    }
    void (async () => {
      const res = await onSubmitRef.current("", "professional");
      if (res && typeof res === "object" && "caption" in res && typeof res.caption === "string") {
        setCaptionResult(res.caption);
        setEditText(res.caption);
        setEditing(false);
      } else if (typeof res === "string") {
        setCaptionResult(res);
        setEditText(res);
        setEditing(false);
      }
    })();
  }, [open]);

  // Sync chat textarea height between 38px (1 line) and 120px
  useEffect(() => {
    const el = chatTextareaRef.current;
    if (!el) return;
    if (!prompt) {
      el.style.height = "38px";
      return;
    }
    el.style.height = "38px";
    const nextHeight = Math.min(Math.max(el.scrollHeight, 38), 120);
    el.style.height = `${nextHeight}px`;
  }, [prompt, open]);

  const handleGenerate = async (instructionPrompt: string) => {
    if (isOverLimit || isLoading) return;
    const res = await onSubmit(instructionPrompt.trim(), selectedTone);
    if (res && typeof res === "object" && "caption" in res && typeof res.caption === "string") {
      setCaptionResult(res.caption);
      setEditText(res.caption);
      setEditing(false);
      setPrompt("");
    } else if (typeof res === "string") {
      setCaptionResult(res);
      setEditText(res);
      setEditing(false);
      setPrompt("");
    }
  };

  const handleCopyCaption = async () => {
    const textToCopy = editing ? editText : captionResult;
    if (!textToCopy) return;
    try {
      await navigator.clipboard.writeText(textToCopy);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Fallback if clipboard API unavailable
    }
  };

  const handleUse = () => {
    const finalCaption = (editing ? editText : captionResult).trim();
    if (!finalCaption || isLoading) return;
    onApprove(finalCaption, selectedTone, editing ? "use_then_edited" : "use");
  };

  const handleCancelAction = () => {
    if (editing) {
      setEditing(false);
      setEditText(captionResult);
      return;
    }
    onClose();
  };

  if (!open) return null;

  const activeText = editing ? editText : captionResult;
  const hasCaption = Boolean(activeText.trim());

  return createPortal(
    <div
      className="submission-screen ai-prompt-overlay"
      role="presentation"
      onMouseDown={(event) => {
        if (event.target === event.currentTarget && !isLoading) onClose();
      }}
    >
      <section
        className="ai-prompt-dialog"
        role="dialog"
        aria-modal="true"
        aria-labelledby={titleId}
      >
        <div className="ai-prompt-head">
          <div>
            <span className="ai-prompt-kicker">AI Caption Assistant</span>
            <h2 id={titleId}>Suggest Caption</h2>
          </div>
          <button
            type="button"
            className="ai-prompt-icon-btn"
            onClick={onClose}
            disabled={isLoading}
            title="Close"
            aria-label="Close"
          >
            <i className="ti ti-x" aria-hidden />
          </button>
        </div>

        <p className="ai-prompt-context">{contextLabel}</p>

        {isUnsaved && !captionResult && (
          <div className="ai-prompt-save-notice" role="note">
            <i className="ti ti-info-circle" aria-hidden="true" />
            <div>
              <strong>Behind the scenes:</strong> Generating this caption will automatically save
              your draft and upload your event photos first so AI can inspect the image details and
              event context.
            </div>
          </div>
        )}

        {/* AI Caption Result Card with Use / Edit / Cancel */}
        <div className="ai-caption-result-container">
          <div className="ai-caption-result-header">
            <div className="ai-caption-result-title-group">
              <span className="ai-caption-result-label">
                <i className="ti ti-sparkles" aria-hidden="true" />
                <span>AI Draft</span>
              </span>
              {captionResult && (
                <span className="ai-caption-tone-pill">{selectedTone}</span>
              )}
            </div>

            <div className="ai-caption-result-actions">
              {captionResult && !editing && (
                <button
                  type="button"
                  className="ai-caption-copy-btn"
                  onClick={handleCopyCaption}
                  disabled={isLoading}
                  title="Copy caption to clipboard"
                >
                  <i className={copied ? "ti ti-check" : "ti ti-copy"} aria-hidden="true" />
                  <span>{copied ? "Copied" : "Copy"}</span>
                </button>
              )}

              {captionResult && !editing && (
                <button
                  type="button"
                  className="ai-caption-action-btn ai-caption-action-btn--edit"
                  onClick={() => {
                    setEditText(captionResult);
                    setEditing(true);
                  }}
                  disabled={isLoading}
                  title="Edit generated caption"
                >
                  <i className="ti ti-pencil" aria-hidden="true" />
                  <span>Edit</span>
                </button>
              )}

              <button
                type="button"
                className="ai-caption-action-btn ai-caption-action-btn--cancel"
                onClick={handleCancelAction}
                disabled={isLoading}
                title={editing ? "Discard edits" : "Cancel and close"}
              >
                <span>Cancel</span>
              </button>

              {captionResult && (
                <button
                  type="button"
                  className="ai-caption-action-btn ai-caption-action-btn--use"
                  onClick={handleUse}
                  disabled={isLoading || !hasCaption}
                  title="Apply this caption to your post"
                >
                  <i className="ti ti-check" aria-hidden="true" />
                  <span>Use</span>
                </button>
              )}
            </div>
          </div>

          <div className="ai-caption-result-box-wrapper">
            {isLoading && (
              <div className="ai-caption-generating-overlay">
                <span className="ai-caption-spinner-lg" aria-hidden="true" />
                <p>AI is generating your caption...</p>
              </div>
            )}

            {editing ? (
              <textarea
                className="ai-caption-result-edit-textarea"
                value={editText}
                maxLength={3000}
                onChange={(e) => setEditText(e.target.value)}
                rows={5}
                autoFocus
                aria-label="Edit generated caption"
              />
            ) : (
              <div
                className="ai-caption-result-display"
                role="region"
                aria-label="Generated caption preview"
              >
                {captionResult ? (
                  <div className="ai-caption-result-text">{captionResult}</div>
                ) : (
                  <div className="ai-caption-result-placeholder">
                    Generating a caption from your event details and media...
                  </div>
                )}
              </div>
            )}

            <div className="ai-caption-result-footer">
              <span className="ai-caption-result-hint">
                {editing
                  ? "Editing draft — click Use to apply or Cancel to revert."
                  : captionResult
                    ? "Click Use to apply, Edit to tweak, or refine below."
                    : "You can also pick a tone or add instructions below."}
              </span>
              <span className="ai-caption-result-count">{activeText.length} / 3000</span>
            </div>
          </div>
        </div>

        {/* Prompt chat bar: Tone dropdown on the left + auto-growing textarea + Generate/Refine */}
        <div className="ai-prompt-chat-section">
          <form
            className="ai-prompt-chat-bar"
            onSubmit={(e) => {
              e.preventDefault();
              void handleGenerate(prompt);
            }}
          >
            <div className="ai-prompt-tone-select-wrap">
              <label htmlFor={toneSelectId} className="sr-only">
                Caption tone
              </label>
              <i className="ti ti-adjustments-horizontal ai-prompt-tone-icon" aria-hidden="true" />
              <select
                id={toneSelectId}
                className="ai-prompt-tone-select"
                value={selectedTone}
                onChange={(e) => setSelectedTone(e.target.value as CaptionTone)}
                disabled={isLoading}
                aria-label="Caption tone"
              >
                {TONE_OPTIONS.map((option) => (
                  <option key={option.tone} value={option.tone}>
                    {option.label}
                  </option>
                ))}
              </select>
            </div>

            <div className="ai-prompt-chat-input-wrap">
              <textarea
                ref={chatTextareaRef}
                className="ai-prompt-chat-input"
                rows={1}
                value={prompt}
                maxLength={AI_CAPTION_PROMPT_MAX_LENGTH}
                onChange={(e) => setPrompt(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter" && !e.shiftKey) {
                    e.preventDefault();
                    void handleGenerate(prompt);
                  }
                }}
                placeholder={
                  captionResult
                    ? "Refine (e.g. shorter, add hashtags)..."
                    : "Add instructions or leave blank..."
                }
                disabled={isLoading}
                aria-label="AI caption instructions"
              />
            </div>

            <button
              type="submit"
              className="ai-prompt-chat-send-btn"
              disabled={isLoading || isOverLimit}
              title={captionResult ? "Regenerate or refine caption" : "Generate caption"}
            >
              {isLoading ? (
                <span className="ai-caption-spinner" aria-hidden="true" />
              ) : captionResult ? (
                <>
                  <i className="ti ti-refresh" aria-hidden="true" />
                  <span>Refine</span>
                </>
              ) : (
                <>
                  <i className="ti ti-sparkles" aria-hidden="true" />
                  <span>Generate</span>
                </>
              )}
            </button>
          </form>
        </div>
      </section>
    </div>,
    document.body,
  );
}
